import { readFile, mkdir, writeFile } from 'node:fs/promises'
import { dirname, resolve } from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'

const destination = new URL('../supabase/upgrades/advance-reminders.sql', import.meta.url)
const migrations = [
  '202610050001_advance_reminders.sql',
  '202610050002_reminder_phone_connections.sql',
  '202610050003_repeating_advance_reminders.sql',
  '202610050006_reminder_reschedule_daily_time.sql'
]

async function migrationBody(filename, tag) {
  const source = await readFile(new URL(`../supabase/migrations/${filename}`, import.meta.url), 'utf8')
  if (!/^begin;$/m.test(source) || !/\ncommit;\s*$/.test(source)) throw new Error(`Expected one outer transaction in ${filename}.`)
  if (source.includes(`$${tag}$`) || source.includes('$estate_reminder_upgrade$')) throw new Error(`SQL delimiter conflict in ${filename}.`)
  return source.replace(/^begin;\r?\n/m, '').replace(/\ncommit;\s*$/, '\n').trimEnd()
}

export async function generateReminderUpgrade() {
  const [base, connections, daily, fix] = await Promise.all(migrations.map((filename, index) => migrationBody(filename, `reminder_${index + 1}`)))
  return `-- Generated by node scripts/generate-reminder-upgrade.mjs. Do not edit by hand.
-- Paste this ENTIRE file into Supabase SQL Editor and run it as one query.
-- Requires the estate application's earlier schema migrations through
-- 202610040001_remove_joint_loans.sql. Adds only missing reminder migrations.
-- Existing settings, subscriptions, payment records and delivery history remain.
-- Safe to run again after a successful upgrade. Edge Functions deploy separately.
begin;

-- Serialize this upgrade across SQL Editor sessions.
select pg_advisory_xact_lock(20261005, 6);

do $estate_reminder_upgrade$
declare
  v_base_count integer;
  v_daily_count integer;
begin
  select count(*) into v_base_count
  from unnest(array[
    'public.advance_reminder_settings', 'public.advance_push_subscriptions',
    'public.weekly_pay_runs', 'public.advance_reminder_deliveries'
  ]) as required(name)
  where to_regclass(required.name) is not null;

  if v_base_count not in (0, 4) then
    raise exception 'The base reminder schema is incomplete. No changes were applied. Inspect migration 202610050001_advance_reminders.sql before upgrading.';
  end if;
  if v_base_count = 0 then
    if to_regclass('public.workers') is null or to_regclass('public.weekly_payments') is null
      or to_regclass('public.worker_loans') is null or to_regprocedure('public.touch_updated_at()') is null then
      raise exception 'Apply the earlier estate schema migrations before this reminder upgrade. No changes were applied.';
    end if;
    execute $reminder_1$
${base}
$reminder_1$;
  end if;

  -- Check all markers together: a partially edited daily schema is unsafe to
  -- guess at. Clean older installations have none; upgraded ones have all nine.
  select count(*) into v_daily_count from unnest(array[
    exists (select 1 from pg_attribute where attrelid = 'public.advance_reminder_settings'::regclass and attname = 'revision' and not attisdropped),
    exists (select 1 from pg_attribute where attrelid = 'public.advance_reminder_deliveries'::regclass and attname = 'kind' and not attisdropped),
    exists (select 1 from pg_attribute where attrelid = 'public.advance_reminder_deliveries'::regclass and attname = 'settings_revision' and not attisdropped),
    to_regclass('public.advance_reminder_weeks') is not null,
    exists (select 1 from pg_constraint where conrelid = 'public.advance_reminder_deliveries'::regclass and conname = 'advance_reminder_delivery_occurrence_key' and contype = 'u'),
    to_regprocedure('public.prepare_advance_reminder_settings()') is not null,
    to_regprocedure('public.queue_advance_reminder_reschedule()') is not null,
    exists (select 1 from pg_trigger where tgrelid = 'public.advance_reminder_settings'::regclass and tgname = 'advance_reminder_settings_updated' and tgfoid = to_regprocedure('public.prepare_advance_reminder_settings()') and not tgisinternal and tgenabled <> 'D'),
    exists (select 1 from pg_trigger where tgrelid = 'public.advance_reminder_settings'::regclass and tgname = 'advance_reminder_rescheduled' and tgfoid = to_regprocedure('public.queue_advance_reminder_reschedule()') and not tgisinternal and tgenabled <> 'D')
  ]) as marker(installed) where marker.installed;

  if v_daily_count not in (0, 9) then
    raise exception 'The daily reminder schema is partially installed. No changes were applied. Inspect migration 202610050003_repeating_advance_reminders.sql before upgrading.';
  end if;
  if v_daily_count = 9 and exists (
    select 1 from pg_constraint where conrelid = 'public.advance_reminder_deliveries'::regclass
      and conname = 'advance_reminder_deliveries_user_id_week_start_endpoint_key'
  ) then
    raise exception 'The old weekly delivery constraint still exists. The daily reminder migration is incomplete; no changes were applied.';
  end if;

  if not exists (
    select 1 from pg_attribute where attrelid = 'public.advance_push_subscriptions'::regclass
      and attname = 'connected_at' and not attisdropped and attnotnull
  ) then
    if v_daily_count <> 0 then
      raise exception 'The daily reminder schema is missing its phone connection prerequisite. No changes were applied.';
    end if;
    execute $reminder_2$
${connections}
$reminder_2$;
  end if;

  if v_daily_count = 0 then
    execute $reminder_3$
${daily}
$reminder_3$;
  end if;

  execute $reminder_4$
${fix}
$reminder_4$;
end;
$estate_reminder_upgrade$;

notify pgrst, 'reload schema';
commit;

select 'Reminder database upgrade complete' as result,
  to_regclass('public.advance_reminder_weeks') is not null as daily_tracking_ready,
  to_regprocedure('public.queue_advance_reminder_reschedule()') is not null as reschedule_ready;
`
}

if (process.argv[1] && pathToFileURL(resolve(process.argv[1])).href === import.meta.url) {
  try {
    const sql = await generateReminderUpgrade()
    if (process.argv[2] === '--check') {
      if (await readFile(destination, 'utf8') !== sql) throw new Error('Reminder upgrade SQL is stale. Run node scripts/generate-reminder-upgrade.mjs.')
      console.log('Reminder upgrade SQL matches its source migrations.')
    } else if (process.argv.length > 2) {
      throw new Error('Usage: node scripts/generate-reminder-upgrade.mjs [--check]')
    } else {
      await mkdir(dirname(fileURLToPath(destination)), { recursive: true })
      await writeFile(destination, sql)
      console.log(`Created ${fileURLToPath(destination)}. Run the whole file in Supabase SQL Editor.`)
    }
  } catch (error) {
    console.error(error.message)
    process.exitCode = 1
  }
}
